"""Helpers for the rules book (used by build_rules.py): an index of the chapter files, a search for every mention of a term, and consistency checks.

    python3 build_rules.py                      builds the seven documents, rewrites rules-src/INDEX.md and prints the checks
    python3 build_rules.py --where Engaged      every mention of a term (several terms may be given)
Run them from the folder that holds rules-src/.
"""
import os, re

CHAPTER = re.compile(r'^\d\d-.*\.md$')
CALLOUTS = {'example', 'tbd', 'note', 'tip'}
norm = lambda s: re.sub(r'[^a-z0-9]', '', re.sub(r'<[^>]+>', '', s).lower())
plain = lambda s: re.sub(r'\[\[(?:[^\]|]*\|)?([^\]]*)\]\]', r'\1', re.sub(r'\\\|', '|', s)).replace('**', '').replace('*', '').strip()

def chapter_files(src):
    return sorted(f for f in os.listdir(src) if CHAPTER.match(f))

def parse(src):
    """Reads every chapter file: headings, Action cards, open (TBD) boxes, glossary entries and callouts."""
    out = {}
    for fn in chapter_files(src):
        lines = open(os.path.join(src, fn)).read().split('\n')
        d = dict(lines=lines, title='', part='', doc='core', headings=[], cards=[], tbds=[], glossary=[], callouts=[], size=os.path.getsize(os.path.join(src, fn)))
        card = None
        for n, l in enumerate(lines, 1):
            pm = re.match(r'<!-- part: (.*?) -->', l)
            if pm: d['part'] = pm.group(1)
            dm = re.match(r'<!-- doc: (\w+) -->', l)
            if dm: d['doc'] = dm.group(1)
            hm = re.match(r'^(#{1,4}) (.+?)\s*$', l)
            if hm:
                if len(hm.group(1)) == 1 and not d['title']: d['title'] = hm.group(2)
                d['headings'].append((n, len(hm.group(1)), hm.group(2)))
            am = re.search(r'<div class="action-head"><span>(.*?)</span>(?:<span>(.*?)</span>)?(?:<span class="cat">(.*?)</span>)?', l)
            if am:
                card = dict(line=n, name=am.group(1), cost=am.group(2) or '', cat=am.group(3) or '', freq='')
                d['cards'].append(card)
            fm = re.match(r'^\*\*Frequency:\*\*\s*(.+)$', l)
            if fm and card and not card['freq']: card['freq'] = fm.group(1).strip()
            if l.startswith('</div>'): card = None
            cm = re.match(r'^> \[!(\w+)\]\s*$', l)
            if cm:
                d['callouts'].append((n, cm.group(1)))
                if cm.group(1) == 'tbd':
                    body = ''
                    if n < len(lines) and lines[n].startswith('>'): body = re.sub(r'^> ?', '', lines[n])
                    d['tbds'].append((n, body))
            if fn.startswith('09-') and l.startswith('| [['):
                cell = re.split(r'(?<!\\)\|', l)[1]   # the first cell (the pipes written \| belong to the cross-reference)
                tm = re.search(r'\*\*(.+?)\*\*', cell); xm = re.match(r'\s*\[\[(.*?)(?:\\\|.*)?\]\]', cell)
                if tm: d['glossary'].append((n, tm.group(1), xm.group(1) if xm else ''))
        out[fn] = d
    return out

# ------------------------------------------------------------------ INDEX.md
def write_index(parsed, src):
    L = ['# Index of rules-src (generated by build_rules.py: do not edit)', '',
         'Run from the folder that holds `rules-src/`: `python3 build_rules.py` rebuilds the seven documents (`core-rules.html`, `species.html`, `paladin.html`, `archer.html`, `bestiary.html`), rewrites this index and prints the checks; `python3 build_rules.py --where Engaged` lists every mention of a term. See `README.md` for how the files are written.', '',
         '| File | Chapter | Document | Part | KB | Lines |', '|---|---|---|---|---|---|']
    for fn, d in parsed.items(): L.append(f'| {fn} | {d["title"]} | {d["doc"]} | {d["part"]} | {d["size"] / 1024:.1f} | {len(d["lines"])} |')
    for fn, d in parsed.items():
        L += ['', f'## {fn}: {d["title"]}', '']
        for n, lv, t in d['headings'][1:]:
            L.append(f'- {n}: {"  " * (lv - 2)}{"#" * lv} {plain(t)}')
        if d['cards']:
            L += ['', 'Action cards: ' + '; '.join(f'{c["name"]} ({c["line"]}{", " + c["cat"] if c["cat"] else ""}{", " + c["freq"] if c["freq"] else ""})' for c in d['cards'])]
        if d['tbds']:
            L += ['', 'Open (to be decided) boxes: ' + '; '.join(f'{n}: "{plain(b)[:70]}"' for n, b in d['tbds'])]
        if d['glossary']:
            L += ['', 'Glossary entries (line: term): ' + '; '.join(f'{n}: {plain(t)}' for n, t, _ in d['glossary'])]
    open(os.path.join(src, 'INDEX.md'), 'w').write('\n'.join(L) + '\n')

# ------------------------------------------------------------------ --where
def where(src, terms):
    parsed = parse(src)
    for term in terms:
        rx = re.compile(r'(?<![A-Za-z0-9])' + re.escape(term) + r'(?![A-Za-z0-9])', re.I)
        hits = []; defs = []; head = []; gloss = []
        for fn, d in parsed.items():
            section = ''
            for n, l in enumerate(d['lines'], 1):
                hm = re.match(r'^#{1,4} (.+?)\s*$', l)
                if hm: section = plain(hm.group(1))
                if not rx.search(l): continue
                kind = 'heading' if hm and rx.search(hm.group(1)) else 'glossary' if fn.startswith('09-') and l.startswith('| [[') else 'defined' if re.search(r'\*\*[^*]*' + re.escape(term) + r'[^*]*\*\*', l, re.I) and not l.startswith('|') and not l.startswith('<') else 'xref' if re.search(r'\[\[[^\]]*' + re.escape(term) + r'[^\]]*\]\]', l, re.I) and not rx.search(re.sub(r'\[\[.*?\]\]', '', l)) else 'text'
                hits.append((fn, n, kind, section, l.strip()))
        print(f'\n== {term}: {len(hits)} mention{"s" if len(hits) != 1 else ""} in {len({h[0] for h in hits})} file{"s" if len({h[0] for h in hits}) != 1 else ""}')
        for label, k in (('Heading', 'heading'), ('Defined (bold)', 'defined'), ('Glossary', 'glossary')):
            at = [f'{h[0]}:{h[1]}' for h in hits if h[2] == k]
            if at: print(f'   {label}: ' + ', '.join(at))
        cur = None
        for fn, n, kind, section, text in hits:
            if fn != cur: print(f'  {fn}'); cur = fn
            snippet = plain(text)
            m = rx.search(snippet); a = max(0, (m.start() if m else 0) - 45)
            print(f'    {n:>4} [{section[:28]}] {kind if kind != "text" else ""}{" " if kind != "text" else ""}{("…" if a else "") + snippet[a:a + 115]}')

# ------------------------------------------------------------------ checks
def report(parsed, doc_html):
    """Consistency checks of the sources and the built book (they inform, they never stop the build)."""
    out = []
    def check(name, items, note=''):
        out.append(f'  {"ok  " if not items else "warn"} {name}' + (f' ({len(items)})' if items else ''))
        for it in items[:8]: out.append(f'         {it}')
        if len(items) > 8: out.append(f'         ... and {len(items) - 8} more')
    # headings that share a title: a [[reference]] to them is ambiguous
    seen = {}
    for fn, d in parsed.items():
        for n, lv, t in d['headings']: seen.setdefault((d['doc'], norm(t)), []).append(f'{fn}:{n} {plain(t)}')   # (a repeat in another document is meant: each has its own Features, Actions...)
    # (a title repeated inside one file is meant: each class has its own Actions and Features)
    check('headings with the same title in different files', [' | '.join(v) for v in seen.values() if len({x.split(':')[0] for x in v}) > 1])
    dup = {k: v for k, v in seen.items() if len(v) > 1}   # (document, title) -> where it repeats
    links = []
    for fn, d in parsed.items():
        for n, l in enumerate(d['lines'], 1):
            for m in re.finditer(r'\[\[([^\]|\\]+)', l):
                if (d['doc'], norm(m.group(1))) in dup: links.append(f'{fn}:{n} [[{m.group(1)}]] goes to the first: {dup[(d["doc"], norm(m.group(1)))][0]}')
    check('links to a title that exists more than once (they go to the first)', links)
    # glossary entries that no other chapter uses
    gl = parsed.get('09-glossary.md', {}).get('glossary', [])
    body = '\n'.join('\n'.join(d['lines']) for fn, d in parsed.items() if not fn.startswith('09-'))
    parts_of = lambda t: [x.strip() for x in re.split(r',| / ', plain(t).split(' (')[0]) if x.strip()]   # "Bane, Boon" are two terms
    unused = [f'{n}: {plain(t)}' for n, t, _ in gl if not any(re.search(r'(?<![A-Za-z0-9])' + re.escape(x) + r'(?![A-Za-z0-9])', body, re.I) for x in parts_of(t))]
    check('glossary entries that no other chapter mentions', unused)
    # rule headings without a glossary entry (informational)
    known = {norm(plain(t)) for _, t, _ in gl} | {norm(x) for _, _, x in gl}
    rule_files = ('01-', '02-', '03-', '04-', '08-')
    nogl = [f'{fn}:{n} {plain(t)}' for fn, d in parsed.items() if fn.startswith(rule_files) for n, lv, t in d['headings'] if lv in (2, 3) and norm(t) not in known]
    check('rule headings without a glossary entry (many are fine)', nogl)
    # callouts and cards
    check('callouts of an unknown kind', [f'{fn}:{n} [!{k}]' for fn, d in parsed.items() for n, k in d['callouts'] if k not in CALLOUTS])
    cards = [(fn, c) for fn, d in parsed.items() for c in d['cards']]
    names = {}
    for fn, c in cards: names.setdefault(c['name'].lower(), []).append(f'{fn}:{c["line"]}')
    check('Action cards with the same name', [f'{k}: ' + ', '.join(v) for k, v in names.items() if len(v) > 1])
    check('Action cards without a Frequency (Talents and Features may have none)', [f'{fn}:{c["line"]} {c["name"]}' for fn, c in cards if not c['freq'] and not re.search(r'Talent|Feature|Blessing|Escalation', c['cat'])])
    # the names of the examples (README: "Names in the examples"): only these, he/him or she/her as listed; a name is not repeated before all are used
    NAMES = {n: 'he' for n in 'Dave Jared Zack Nari Drak Wes John Steven Mark Jacob Chris Lonny Nick Will Philip Peter Paul Victor'.split()}; NAMES.update({'Krysta': 'she', 'Lana': 'she'})
    OLD = ('Kai', 'Mara', 'Rin', 'Tor')   # names that were in the book before the list
    text_lines = [(fn, n, l) for fn, d in parsed.items() if fn[:2] in ('01', '02', '03', '04', '05', '06', '07', '08') for n, l in enumerate(d['lines'], 1)]
    check('names of the examples that are not in the list', [f'{fn}:{n} {w}' for fn, n, l in text_lines for w in OLD if re.search(r'\b' + w + r'\b', l)])
    bad = []
    for fn, n, l in text_lines:
        found = {w for w in NAMES if re.search(r'\b' + w + r'\b', l)}
        if len(found) == 1:
            w = found.pop(); male = re.search(r'\b(he|him|his|himself)\b', l, re.I); female = re.search(r'\b(she|her|hers|herself)\b', l, re.I)
            if (NAMES[w] == 'he' and female and not male) or (NAMES[w] == 'she' and male and not female): bad.append(f'{fn}:{n} {w}: {re.sub(chr(10), " ", l)[:90]}')
    check('a name and its pronouns do not match (lines with one name)', bad)
    use = {w: sum(len(re.findall(r'\b' + w + r'\b', l)) for fn, n, l in text_lines) for w in NAMES}
    out.append('  info names used: ' + ', '.join(f'{w} {c}' for w, c in use.items() if c) + ' | never used: ' + ', '.join(w for w, c in use.items() if not c))
    left = sorted(set(re.findall(r'@@\w+@@|\{\{[^}]*\}\}', re.sub(r'<style>.*?</style>', '', doc_html, flags=re.S))))
    check('placeholders left in the built book', left)
    out.append(f'  info {sum(len(d["tbds"]) for d in parsed.values())} open (to be decided) boxes; {len(cards)} Action cards; {len(gl)} glossary entries')
    print('CHECKS\n' + '\n'.join(out))
